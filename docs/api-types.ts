// ============================================================ sync rows

/** Fields common to every synced row sent by the client. */
export interface SyncRowIn {
  /** Client-generated UUID. */
  id: UUID;
  /** Client clock, ISO 8601 (no offset = UTC). Bump it on EVERY change (last write wins). */
  updated_at: IsoDateTime;
  /** Soft delete. Default false. */
  deleted?: boolean;
}

export interface PlotIn extends SyncRowIn {
  zone_id: string;
  /** 1..128 characters (trimmed). */
  name: string;
  /** 0 < area_ha ≤ 100, or null. */
  area_ha?: number | null;
  soil_id?: string | null;
}

export interface PlotSeasonIn extends SyncRowIn {
  /** A plot of this device (already on the server, or in the same push). */
  plot_id: UUID;
  /** 1..32 characters, e.g. "2026-main". */
  season_label: string;
  crop_id?: string | null;
  sowing_date?: IsoDate | null;
  /** ≤ 1000 characters */
  yield_note?: string | null;
  /** ≤ 1000 characters */
  losses_note?: string | null;
}

export interface PostIn extends SyncRowIn {
  zone_id: string;
  /** 1..1000 characters (trimmed). */
  body: string;
}

/** Rows as returned by the server. */
export interface PlotOut {
  id: UUID;
  zone_id: string;
  name: string;
  area_ha: number | null;
  soil_id: string | null;
  updated_at: IsoDateTime;
  deleted: boolean;
  server_updated_at: IsoDateTime;
}

export interface PlotSeasonOut {
  id: UUID;
  plot_id: UUID;
  season_label: string;
  crop_id: string | null;
  sowing_date: IsoDate | null;
  yield_note: string | null;
  losses_note: string | null;
  updated_at: IsoDateTime;
  deleted: boolean;
  server_updated_at: IsoDateTime;
}

/** Post as seen by everyone (GET /posts, zone summary): no device_id, no is_mine. */
export interface PublicPost {
  id: UUID;
  zone_id: string;
  /** "" for a deleted post of ANOTHER device (tombstone). */
  body: string;
  updated_at: IsoDateTime;
  deleted: boolean;
  server_updated_at: IsoDateTime;
  /** Author's display_name (may be null). */
  author_name: string | null;
}

/** Post as seen by an authenticated device (pull, POST/DELETE /posts, stale server_row). */
export interface PostOut extends PublicPost {
  is_mine: boolean;
}

// ============================================================ sync push / pull

/** POST /sync/push — at most 500 rows per array (else 422). */
export interface PushRequest {
  changes: {
    plots?: PlotIn[];
    plot_seasons?: PlotSeasonIn[];
    posts?: PostIn[];
  };
}

export type SyncEntity = "plots" | "plot_seasons" | "posts";

export type RejectReason =
  | "invalid"
  | "unknown_zone"
  | "unknown_soil"
  | "unknown_crop"
  | "unknown_plot"
  | "forbidden"
  | "stale";

export interface RejectedRow {
  /** id of the rejected row (null if the row had no id). */
  id: string | null;
  entity: SyncEntity;
  reason: RejectReason;
  message_fr: string;
  /** Only for "stale": the newer server version of the row. */
  server_row: PlotOut | PlotSeasonOut | PostOut | null;
}

export interface PushResponse {
  /** ids applied (including idempotent replays). */
  accepted: UUID[];
  rejected: RejectedRow[];
  /** Informative only. NOT a pull cursor: use the server_time of GET /sync/pull. */
  server_time: IsoDateTime;
}

/** GET /sync/pull?since=<cursor> */
export interface PullResponse {
  changes: {
    plots: PlotOut[];
    plot_seasons: PlotSeasonOut[];
    /** Own posts + public posts of the device's zone (tombstones included). */
    posts: PostOut[];
  };
  /** Next cursor (store it). May be up to 5 s in the past: rows can come twice, upsert by id. */
  server_time: IsoDateTime;
  /** Not null = more pages: call again immediately with since=next_since. */
  next_since: IsoDateTime | null;
}

