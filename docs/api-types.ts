export interface ApiErrorDetail {
  /** Path of the invalid field, e.g. ["body", "device_id"]. */
  loc: string[];
  /** Technical message (English, from the validator): never show it to farmers. */
  msg: string;
}

/** Body of EVERY error response (4xx and 5xx). The OpenAPI schema says {detail: ...} for 422: wrong. */
export interface ApiErrorResponse {
  error: {
    code: ApiErrorCode;
    /** French message, can be shown to the user. */
    message_fr: string;
    /** Only on some 422 validation_error responses. */
    details?: ApiErrorDetail[];
  };
}

