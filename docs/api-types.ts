// ============================================================ golden test file (packs/golden_cases.json)

export type GoldenCase =
  | { case_id: string; function: "simulate"; input: SimulateRequest; expected_output: SimulationResult }
  | { case_id: string; function: "recommend"; input: RecommendRequest; expected_output: RotationResult }
  | {
      case_id: string;
      function: "evaluate_sequence";
      input: RecommendRequest & { sequence: string[] };
      expected_output: RotationResult;
    };

export interface GoldenFile {
  golden_version: number;
  generated_at: IsoDateTime;
  generator: string;
  comparison: { numbers_abs_tolerance: number; strict: string[]; note: string };
  packs: Record<string, { file: string; pack_version: string; sha256: string; climate_source_type: SourceType }>;
  embedded_packs: Record<string, ZonePack>;
  cases: GoldenCase[];
}
