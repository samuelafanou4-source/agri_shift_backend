/**
 * Field Shift Togo API — TypeScript types for the frontend.
 *
 * Base URL: https://agri-shift-api.fastapicloud.dev/api/v1
 * Built from the production OpenAPI schema (/openapi.json), the zone pack JSON Schema
 * (packs/zone_pack.schema.json) and, where OpenAPI only says `object`, from the API code
 * (the code is the reference). Checked against real production responses with `tsc --noEmit`.
 * Human documentation: docs/API_FRONTEND.md.
 *
 * Conventions
 * - Dates: ISO 8601 strings in UTC with a "Z" suffix (e.g. "2026-11-08T18:44:08.043904Z").
 * - Calendar dates (sowing_date): "YYYY-MM-DD".
 * - UUIDs: lowercase strings, generated by the client for every entity it creates.
 * - Engine numbers are rounded to 2 decimals by the server (tolerance 0.01 for comparisons).
 * - Fields typed `T | null` are always present in responses (value may be null).
 */

